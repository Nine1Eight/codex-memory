#!/usr/bin/env python3
import sys

# ─── CANONS (MUST BE EXACTLY 111 EACH) ──────────────────────────────────────
VISIBLE_111 = [chr(c) for c in range(0xE000, 0xE06F)]
INVISIBLE_111 = [
"⠀","⠁","⠂","⠃","⠄","⠅","⠆","⠇","⠈","⠉","⠊","⠋","⠌","⠍","⠎","⠏",
"⠐","⠑","⠒","⠓","⠔","⠕","⠖","⠗","⠘","⠙","⠚","⠛","⠜","⠝","⠞","⠟",
"⠠","⠡","⠢","⠣","⠤","⠥","⠦","⠧","⠨","⠩","⠪","⠫","⠬","⠭","⠮","⠯",
"⠰","⠱","⠲","⠳","⠴","⠵","⠶","⠷","⠸","⠹","⠺","⠻","⠼","⠽","⠾","⠿",
"⡀","⡁","⡂","⡃","⡄","⡅","⡆","⡇","⡈","⡉","⡊","⡋","⡌","⡍","⡎","⡏",
"⡐","⡑","⡒","⡓","⡔","⡕","⡖","⡗","⡘","⡙","⡚","⡛","⡜","⡝","⡞","⡟",
"⡠","⡡","⡢","⡣","⡤","⡥","⡦","⡧","⡨","⡩","⡪","⡫","⡬"
]

SIGIL_111 = [
"✶","✷","✸","✹","✺","✻","✼","✽","✾","✿","❀","❁","❂","❃","❄","❅",
"❆","❇","❈","❉","❊","❋","★","☆","✩","✪","✫","✬","✭","✮","✯","✰",
"✱","✲","✳","✴","✵","☀","☁","☂","☃","☄","☼","☽","☾","♠","♡","♣",
"♤","♦","❤","⚡","⚔","☯","⚛","⚗","⚙","⚒","⚚","⚕","⚖","⚘","⊏","⊐",
"⚓","⚑","〇","⟁","⧖","⧗","⧘","⧙","⧚","⧛","⟐","⟑","⟒","⟓","⟔","⟕",
"⟖","⟗","⟘","⟙","⟜","⟝","⟞","⟟","⟠","⟡","⟢","⟣","⟤","⟥","⟦","⟧",
"⟨","⟩","⟪","⟫","⟬","⟭","⟮","⟯","⦀","⦁","⦂","⦃","⦄","⦅"
]

# ─── READ VISIBLE STREAM ───────────────────────────────────────────────────
data = sys.stdin.read()
if not data:
    sys.exit("empty input")

# ─── DERIVE THREE INDEPENDENT INDICES ──────────────────────────────────────
v_acc = 0
i_acc = 0
count = 0

for pos, ch in enumerate(data):
    if ch in VISIBLE_111:
        v = VISIBLE_111.index(ch)
        v_acc = (v_acc + v) % 111
        i_acc = (i_acc + pos) % 111
        count += 1

if count == 0:
    sys.exit("no visible glyphs")

# ─── FINAL SINGLE SIGIL (3×111 PLANES) ──────────────────────────────────────
sigil = SIGIL_111[count % 111]
invis = INVISIBLE_111[i_acc]
vis   = VISIBLE_111[v_acc]

# ONE SYMBOL, THREE PLANES
sys.stdout.write(sigil + invis + vis)
